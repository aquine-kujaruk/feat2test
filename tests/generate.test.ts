import { mkdtemp, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { afterEach, beforeEach, describe, expect, test } from 'vitest'
import type { CodegenError } from '../src/errors.js'
import { generate, outputPrefix } from '../src/generate.js'

let workspace = ''

beforeEach(async () => {
  workspace = await mkdtemp(path.join(tmpdir(), 'feat2test-'))
})

afterEach(async () => {
  await rm(workspace, { recursive: true, force: true })
})

/** Writes a Feature and generates from it, returning both outputs. */
async function run(
  source: string,
  { filename = 'shop.feature.md', check = false } = {},
): Promise<{ steps: string; test: string; warnings: readonly string[] }> {
  const input = path.join(workspace, filename)
  await writeFile(input, source, 'utf8')
  const report = await generate(input, workspace, { check, runner: 'vitest' })
  return {
    steps: await read(report.stepAdapterPath),
    test: await read(report.testPath),
    warnings: report.warnings,
  }
}

async function read(target: string): Promise<string> {
  return await readFile(target, 'utf8').catch(() => '')
}

async function failure(source: string, filename = 'shop.feature.md'): Promise<CodegenError> {
  const input = path.join(workspace, filename)
  await writeFile(input, source, 'utf8')
  try {
    await generate(input, workspace, { runner: 'vitest' })
  } catch (error) {
    return error as CodegenError
  }
  throw new Error('expected generation to fail')
}

